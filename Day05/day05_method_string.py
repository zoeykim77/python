stduents = input('학생이름을 입력해주세요').split('')

# 2) join : 문자열 원소로 가지는 컨테이너 각 값을 이어붙임 (구분자 기준)
# 문자열은 수정불가하기에, 새로운 문자열로 반환 
# 흩어진 문자열을 붙이는 용도로 활용
# ""(붙여줄 말 혹은 공백).join(대상문자열) 

answer = "~".join(students) #공백 대신 ~로 구분해 반환, 수정하기에 새롭게 반환! 

# 문자열만 속성! 숫자가 들어오면 에러, 숫자는 문자로 바꾸고 해줘야함 (매핑=변경치환)
