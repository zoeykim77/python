#3) strip : 문자열 처리 
# 특정 문자열 제거 가능
# .strip() 공백제거, .lstrip 왼쪽공백제거

word = '   오늘 하루도 힘내 봅시다~   ' #공백도 인식, 31글자 

# 문자열은 불변 자료형! 그자체 못바꿈. 새로운 문자열 반환! 

word.strip() #기존 문자열 변경x (문자열은 불변자료형)
clean_word=word.lstrip() #왼쪽 공백 삭제 가능 

# 4) find, index : 특정 문자의 위치를 확인하는 메서드 

idx = clean_word.index('짠') # 문자열로 찾아 인덱스 반환, 인덱스에 없을시 에러  
idx = clean_word.find('짠') # 문자열로 찾아서 인덱스로 반환, 없을 경우 -1

# 5) count : 수세기 
# 6) replace : 원하는 값으로 대체  
# 문자열은 불변->반환 
# 존재하지 않은 문자열 대체요청시, 기존 그대로 반환! 

clean_word.replacee('힘','살아') # 힘-> 살아로 
clean_word.replacee('','~') # 공백->~로 

