# 문제: 1부터 100까지의 숫자 중에서 3의 배수만 추출하고,
# 그 중에서 처음 10개와 마지막 5개를 각각 출력하세요.

# 힌트: range()와 리스트 슬라이싱을 사용하세요.
# 해답 코드
multiples_of_3 = []
for i in range(1, 101):
    if i % 3 == 0:
        multiples_of_3.append(i)

# 처음 10개와 마지막 5개 추출
first_10 = multiples_of_3[:10]
last_5 = multiples_of_3[-5:]

print(f"처음 10개: {first_10}")
print(f"마지막 5개: {last_5}")

# 출력 예시
# 처음 10개: [3, 6, 9, 12, 15, 18, 21, 24, 27, 30]
# 마지막 5개: [87, 90, 93, 96, 99] 